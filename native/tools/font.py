#!/usr/bin/env python3
"""Build a small antialiased Noto Sans CJK bitmap subset (SIL OFL 1.1)."""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font_path = Path(sys.argv[1])
output = Path(sys.argv[2])
source = (root / 'src/ui.c').read_text()
chars = sorted(set(chr(i) for i in range(32, 127)) | {c for c in source if ord(c) > 127})
pixels = bytearray()
glyphs = []
for size in (18, 28):
    font = ImageFont.truetype(str(font_path), size, index=2)
    for c in chars:
        advance = round(font.getlength(c))
        width, height = advance + 3, size + 12
        image = Image.new('L', (width, height))
        ImageDraw.Draw(image).text((0, -3), c, font=font, fill=255)
        glyphs.append((ord(c), len(pixels), width, height, advance, size))
        pixels.extend(image.tobytes())
with output.open('w') as out:
    out.write('/* Generated by tools/font.py. Noto Sans CJK subset; see assets/FONT-LICENSE.txt. */\n')
    out.write('#include <stdint.h>\nstruct glyph {uint32_t code,offset;uint16_t width,height,advance,size;};\n')
    out.write('const struct glyph font_glyphs[] = {\n')
    for g in glyphs:
        out.write('{' + ','.join(map(str, g)) + '},\n')
    out.write('};\nconst unsigned font_count = sizeof(font_glyphs)/sizeof(font_glyphs[0]);\n')
    out.write('const unsigned char font_pixels[] = {\n')
    for offset in range(0, len(pixels), 40):
        out.write(','.join(map(str, pixels[offset:offset+40])) + ',\n')
    out.write('};\n')
print(f'{len(glyphs)} glyphs; {len(pixels)} bytes')
